using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;

namespace PowerSimBuilder
{
    /// <summary>
    /// StaTableProject モデルから Python の controller_box.py を生成する。
    /// Phase 1: direct イベントのみ対応。queue は Phase 2。
    /// </summary>
    public class StaTableCodeGenerator
    {
        /// <summary>生成時刻（テスト時に固定可能）</summary>
        public DateTime GeneratedAt { get; set; }

        public StaTableCodeGenerator()
        {
            GeneratedAt = DateTime.Now;
        }

        // ==============================================================
        // Public API
        // ==============================================================

        /// <summary>Python ソースコードを文字列として返す</summary>
        public string Generate(StaTableProject project)
        {
            if (project == null)
                throw new ArgumentNullException("project");

            var sb = new StringBuilder();
            WriteHeader(sb, project);
            WriteImports(sb);
            WriteGlobalVariables(sb, project);
            WriteLayerClasses(sb, project);
            WriteRuntimeBuilder(sb, project);
            WriteEntryPoint(sb);
            return sb.ToString();
        }

        /// <summary>指定パスに Python ファイルを書き出す</summary>
        public void GenerateToFile(StaTableProject project, string filePath)
        {
            var code = Generate(project);
            File.WriteAllText(filePath, code, new UTF8Encoding(false));
        }

        // ==============================================================
        // Header
        // ==============================================================

        private void WriteHeader(StringBuilder sb, StaTableProject project)
        {
            sb.AppendLine("\"\"\"Controller Box - Auto-generated by PowerSimBuilder");
            sb.AppendLine();
            if (!string.IsNullOrEmpty(project.SourceFilePath))
                sb.AppendLine("Source file: " + project.SourceFilePath.Replace("\\", "/"));
            if (!string.IsNullOrEmpty(project.SourceXmlHash))
                sb.AppendLine("Source SHA256: " + project.SourceXmlHash);
            sb.AppendLine("StaTable project: " + project.Name);
            if (project.Settings != null)
            {
                sb.AppendLine("StaTable generation_style: " + project.Settings.GenerationStyle);
                sb.AppendLine("StaTable os_type: " + project.Settings.OsType);
            }
            sb.AppendLine("Tabs: " + project.Tabs.Count
                + " (" + string.Join(", ", project.Tabs.Select(t => t.LayerName)) + ")");
            sb.AppendLine("Generated: " + GeneratedAt.ToString("yyyy-MM-ddTHH:mm:sszzz"));
            sb.AppendLine("\"\"\"");
            sb.AppendLine();
        }

        private void WriteImports(StringBuilder sb)
        {
            sb.AppendLine("from python_runtime.statable import StaTableControllerBase, StaTableRuntime");
            sb.AppendLine();
            sb.AppendLine();
        }

        // ==============================================================
        // Global variables
        // ==============================================================

        private void WriteGlobalVariables(StringBuilder sb, StaTableProject project)
        {
            sb.AppendLine("# ============================================================");
            sb.AppendLine("# Global variables (from GlobalDefinitions.SystemVariables)");
            sb.AppendLine("# ============================================================");
            sb.AppendLine("GLOBAL_VARIABLES = {");

            if (project.GlobalDefinitions != null)
            {
                foreach (var v in project.GlobalDefinitions.SystemVariables)
                {
                    var defaultValue = ConvertToPythonLiteral(v.DefaultValue, v.Type);
                    sb.AppendLine("    \"" + v.Name + "\": " + defaultValue + ",");
                }
            }

            sb.AppendLine("}");
            sb.AppendLine();
            sb.AppendLine();
        }

        private static string ConvertToPythonLiteral(string defaultValue, string type)
        {
            if (string.IsNullOrEmpty(defaultValue))
                return "None";

            // 数値系
            if (type != null &&
                (type.Contains("int") || type.Contains("uint")
                 || type.Contains("long") || type.Contains("short")))
            {
                return defaultValue;
            }
            if (type != null && (type.Contains("float") || type.Contains("double")))
            {
                return defaultValue.Replace(",", ".");
            }
            if (type != null && type.Contains("bool"))
            {
                return (defaultValue == "1" || defaultValue.Equals("true", StringComparison.OrdinalIgnoreCase))
                    ? "True" : "False";
            }
            // それ以外は文字列
            return "\"" + defaultValue.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
        }

        // ==============================================================
        // Layer classes
        // ==============================================================

        private void WriteLayerClasses(StringBuilder sb, StaTableProject project)
        {
            foreach (var layer in project.Tabs)
            {
                WriteLayerClass(sb, layer);
            }
        }

        private void WriteLayerClass(StringBuilder sb, StaTableStateMachine layer)
        {
            var className = MakeClassName(layer.LayerName);

            sb.AppendLine("# ============================================================");
            sb.AppendLine("# Layer: " + layer.LayerName + " (priority " + layer.LayerPriority + ")");
            sb.AppendLine("# ============================================================");
            sb.AppendLine("class " + className + "(StaTableControllerBase):");

            if (!string.IsNullOrEmpty(layer.LayerDescription))
                sb.AppendLine("    \"\"\"" + layer.LayerDescription + "\"\"\"");
            else
                sb.AppendLine("    \"\"\"Layer " + layer.LayerName + "\"\"\"");

            sb.AppendLine();
            sb.AppendLine("    LAYER_NAME = \"" + layer.LayerName + "\"");
            sb.AppendLine("    LAYER_PRIORITY = " + layer.LayerPriority);
            sb.AppendLine("    INITIAL_STATE = \"" + layer.InitialState + "\"");
            sb.AppendLine();

            // TRANSITIONS
            sb.AppendLine("    TRANSITIONS = [");
            sb.AppendLine("        # (source, event, condition, action, target)");
            foreach (var t in layer.Transitions)
            {
                var condition = string.IsNullOrEmpty(t.Condition)
                    ? "None"
                    : "\"" + EscapePy(NCalcToPythonConverter.ConvertCondition(t.Condition)) + "\"";
                var action = string.IsNullOrEmpty(t.Action)
                    ? "None"
                    : "\"" + EscapePy(NCalcToPythonConverter.ConvertAction(t.Action)) + "\"";
                var comment = string.IsNullOrEmpty(t.Title) ? "" : "  # " + t.Title;
                sb.AppendLine("        (\"" + t.Source + "\", \"" + t.Event + "\", "
                    + condition + ", " + action + ", \"" + t.Target + "\")," + comment);
            }
            sb.AppendLine("    ]");
            sb.AppendLine();

            // EVENTS
            sb.AppendLine("    EVENTS = {");
            foreach (var ev in layer.Events)
            {
                sb.Append("        \"" + ev.Name + "\": {\"id\": " + ev.Id
                    + ", \"delivery\": \"" + ev.DeliveryType + "\""
                    + ", \"priority\": " + ev.Priority
                    + ", \"source_layer\": \"" + ev.SourceLayer + "\"");
                if (!string.IsNullOrEmpty(ev.DataName))
                    sb.Append(", \"data_name\": \"" + ev.DataName + "\"");
                sb.AppendLine("},");
            }
            sb.AppendLine("    }");
            sb.AppendLine();

            // __init__
            var compId = MakeCompId(layer.LayerName);
            sb.AppendLine("    def __init__(self, comp_id=\"" + compId + "\"):");
            sb.AppendLine("        super().__init__(");
            sb.AppendLine("            comp_id=comp_id,");
            sb.AppendLine("            comp_type=\"" + className + "\",");
            sb.AppendLine("            layer_name=self.LAYER_NAME,");
            sb.AppendLine("            layer_priority=self.LAYER_PRIORITY,");
            sb.AppendLine("            initial_state=self.INITIAL_STATE,");
            sb.AppendLine("            transitions=self.TRANSITIONS,");
            sb.AppendLine("            events=self.EVENTS,");
            sb.AppendLine("        )");

            // Role functions as methods
            if (layer.RoleFunctions.Count > 0)
            {
                sb.AppendLine();
                sb.AppendLine("    # === Role Functions (from StaTable layer-local) ===");
                foreach (var rf in layer.RoleFunctions)
                {
                    WriteRoleFunction(sb, layer.LayerName, rf);
                }
            }

            sb.AppendLine();
            sb.AppendLine();
        }

        private void WriteRoleFunction(StringBuilder sb, string layerName, StaTableRoleFunction rf)
        {
            var marker = layerName + "." + rf.Name;
            sb.AppendLine("    def " + rf.Name + "(self):");
            sb.AppendLine("        # STABLE_USER_CODE_START:" + marker);
            sb.AppendLine("        return 0");
            sb.AppendLine("        # STABLE_USER_CODE_END:" + marker);
        }

        // ==============================================================
        // Runtime builder
        // ==============================================================

        private void WriteRuntimeBuilder(StringBuilder sb, StaTableProject project)
        {
            sb.AppendLine("# ============================================================");
            sb.AppendLine("# Runtime builder");
            sb.AppendLine("# ============================================================");
            sb.AppendLine("def build_runtime():");
            sb.AppendLine("    layers = [");

            var sorted = project.Tabs
                .OrderBy(t => t.LayerPriority)
                .ToList();
            foreach (var layer in sorted)
            {
                sb.AppendLine("        " + MakeClassName(layer.LayerName) + "(),");
            }

            sb.AppendLine("    ]");
            sb.AppendLine("    return StaTableRuntime(layers, GLOBAL_VARIABLES)");
            sb.AppendLine();
            sb.AppendLine();
        }

        // ==============================================================
        // Entry point
        // ==============================================================

        private void WriteEntryPoint(StringBuilder sb)
        {
            sb.AppendLine("if __name__ == \"__main__\":");
            sb.AppendLine("    rt = build_runtime()");
            sb.AppendLine("    print(f\"StaTable runtime loaded: {len(rt.layers)} layers\")");
        }

        // ==============================================================
        // Utilities
        // ==============================================================

        private static string MakeClassName(string layerName)
        {
            if (string.IsNullOrEmpty(layerName))
                return "UnknownController";
            if (layerName.EndsWith("Controller"))
                return layerName;
            return layerName + "Controller";
        }

        private static string MakeCompId(string layerName)
        {
            if (string.IsNullOrEmpty(layerName))
                return "unknown";
            return layerName.ToLower();
        }

        private static string EscapePy(string s)
        {
            if (s == null) return "";
            return s.Replace("\\", "\\\\").Replace("\"", "\\\"");
        }
    }
}